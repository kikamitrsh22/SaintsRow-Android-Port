# Generates weak stubs for every import in the recompiled code that the runtime doesn't implement.
# Usage: python gen_stubs.py <ppc/ppc_recomp_shared.h> <runtime/src> <output .cpp>
import os
import re
import sys

shared, src_dir, out_path = sys.argv[1:4]

imports = sorted(set(
    m for m in re.findall(r'PPC_EXTERN_FUNC\(__imp__(\w+)\)', open(shared).read())
    if not m.startswith('sub_')
))

implemented = set()
for root, _, files in os.walk(src_dir):
    for f in files:
        if f.endswith('.cpp') and os.path.join(root, f) != os.path.abspath(out_path):
            text = open(os.path.join(root, f), encoding='utf-8').read()
            implemented.update(re.findall(r'GUEST_IMPORT\((\w+)\)', text))
            implemented.update(re.findall(r'NET_FAIL\((\w+)\)', text))

missing = [i for i in imports if i not in implemented]
with open(out_path, 'w', newline='\n') as f:
    f.write('// Generated by runtime/tools/gen_stubs.py - imports with no implementation yet.\n')
    f.write('#include "../guest.h"\n\n')
    for name in missing:
        f.write(f'GUEST_IMPORT({name}) {{ LOG_STUB_ONCE("{name}"); ctx.r3.u64 = 0; }}\n')

print(f'{len(imports)} imports, {len(imports) - len(missing)} implemented, {len(missing)} stubbed')
